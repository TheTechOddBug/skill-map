/**
 * The in-process activity plugin `sm activity install <provider>` writes
 * for `plugin-file` providers (opencode:
 * `.opencode/plugin/skill-map-activity.js`; see
 * `spec/provider-activity.md` §capability, plugin-file paragraph).
 *
 * It is the in-process analog of the spawned bridge, under the SAME
 * contract adapted to running inside the host runtime's process:
 *
 *   - **Invisible (HARD)**: hook callbacks NEVER throw (an exception
 *     inside an in-process hook can alter or block the host session,
 *     the analog of a non-zero exit). Every failure path is a silent
 *     no-op; there is no stdout/stderr surface at all.
 *   - **Dumb**: zero mapping logic. It registers exactly the hooks the
 *     provider's `mapEvent` consumes (the in-process analog of the
 *     `json-hooks` events list), wraps each payload as
 *     `{ hook, directory, ... }` verbatim, and POSTs. All payload
 *     knowledge stays in the Provider's `mapEvent`.
 *   - **Same discovery**: `<directory>/.skill-map/serve.json` read per
 *     event (the plugin context's `directory` IS the project root),
 *     scope + loopback + token checks, 1500ms abort, fail-open.
 *
 * The registered hooks are opencode's: `tool.execute.before` (skill /
 * read / task tools), `command.execute.before`, `chat.message` (named
 * agent + sessionID), and the `event` catch-all FILTERED to
 * `session.idle` (the native owner release). Filtering by event TYPE is
 * wiring, not mapping: it is what keeps the firehose bus (catalog /
 * registry noise) from ever leaving the host process.
 *
 * The template is a source STRING (not a bundled asset) so the CLI can
 * write it anywhere and tests can exercise the exact bytes users get.
 * `{{SM_VERSION}}` is stamped at install time; the header line doubles
 * as the ownership marker install/uninstall/status recognise.
 */

import { VERSION } from '../../version.js';

/** Fetch abort window: a hung server must never hold the host's hook open. */
const PLUGIN_TIMEOUT_MS = 1500;

/** Header marker the engine uses to recognise the file as skill-map's own. */
export const ACTIVITY_PLUGIN_MARKER = 'skill-map activity plugin';

const PLUGIN_TEMPLATE = `// ${ACTIVITY_PLUGIN_MARKER} (generated by \`sm activity install\`, v{{SM_VERSION}}).
// Contract: spec/provider-activity.md §Bridge contract (in-process form).
// Do not edit; re-run the install command to regenerate.
//
// Invariants (HARD): hook callbacks never throw, every failure path is
// a silent no-op, nothing beyond the wrapped raw event leaves the
// process, and only the loopback server named by the project's own
// serve.json is ever contacted.

import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const LOOPBACK_HOSTS = new Set(['127.0.0.1', '::1', 'localhost']);
const TIMEOUT_MS = ${PLUGIN_TIMEOUT_MS};
const PROVIDER = '{{PROVIDER_ID}}';

export const SkillMapActivity = async ({ directory }) => {
  const root = typeof directory === 'string' && directory.length > 0 ? directory : null;

  async function forward(hook, payload) {
    try {
      if (root === null) return;
      const info = JSON.parse(readFileSync(join(root, '.skill-map', 'serve.json'), 'utf8'));
      if (typeof info.scopeRoot !== 'string' || info.scopeRoot !== root) return;
      if (typeof info.host !== 'string' || !LOOPBACK_HOSTS.has(info.host.toLowerCase())) return;
      const controller = new AbortController();
      const timer = setTimeout(() => controller.abort(), TIMEOUT_MS);
      try {
        await fetch('http://' + info.host + ':' + info.port + '/api/activity', {
          method: 'POST',
          headers: {
            'content-type': 'application/json',
            'x-skill-map-token': typeof info.token === 'string' ? info.token : '',
          },
          body: JSON.stringify({ provider: PROVIDER, event: { hook, directory: root, ...payload } }),
          signal: controller.signal,
        });
      } finally {
        clearTimeout(timer);
      }
    } catch {
      // Silent no-op: no server, stale serve.json, unreachable host.
    }
  }

  return {
    'tool.execute.before': async (input, output) => {
      await forward('tool.execute.before', { input, output });
    },
    'command.execute.before': async (input, output) => {
      await forward('command.execute.before', { input, output });
    },
    'chat.message': async (input) => {
      await forward('chat.message', { input });
    },
    event: async ({ event }) => {
      // Wiring-level filter: only the native end signal leaves the
      // process; the rest of the bus (catalog noise) never does.
      if (event && event.type === 'session.idle') {
        await forward('event', { event });
      }
    },
  };
};
`;

/** The exact plugin source `sm activity install` writes for `providerId`. */
export function renderActivityPlugin(providerId: string): string {
  return PLUGIN_TEMPLATE.replace('{{SM_VERSION}}', VERSION).replace('{{PROVIDER_ID}}', providerId);
}
