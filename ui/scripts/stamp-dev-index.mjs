/**
 * Generate `src/index.dev.html` (gitignored) from `src/index.html`,
 * stamping the `skill-map-scope` meta with the ABSOLUTE path of the
 * fixture the dev session serves (`SM_FIXTURE`, default `claude`, the
 * same default `bff:dev` resolves).
 *
 * Why: under `pnpm fix:<fixture>` the HTML comes from the Angular dev
 * server, not the BFF, so the BFF's per-project meta injection never
 * runs; without a scope every fixture shares the `default` storage
 * namespace on the one dev origin (4200) and browser-local project
 * state (the recording tape, node positions) leaks across fixtures,
 * the exact bug the namespace exists to prevent. The static
 * `skill-map-version` `dev` pseudo-version rides through from the
 * source index unchanged.
 *
 * Wired into the ui `dev` script (an inline step, pnpm does not run
 * npm-style pre hooks) and consumed by the `dev-stamped` build
 * configuration that `ng serve --configuration=local` composes on top
 * of `development`. Plain `ng serve` / `ng build` never touch the
 * generated file.
 */

import { readFileSync, realpathSync, writeFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const UI_ROOT = resolve(fileURLToPath(new URL('.', import.meta.url)), '..');
const REPO_ROOT = resolve(UI_ROOT, '..');
const SOURCE = resolve(UI_ROOT, 'src', 'index.html');
const TARGET = resolve(UI_ROOT, 'src', 'index.dev.html');

const fixture = process.env.SM_FIXTURE ?? 'claude';
let fixtureRoot = resolve(REPO_ROOT, 'fixtures', fixture);
if (existsSync(fixtureRoot)) {
  // Realpath so the namespace hash matches what a real `sm serve` of
  // the same fixture would mint (cosmetic: origins differ anyway).
  fixtureRoot = realpathSync(fixtureRoot);
} else {
  process.stderr.write(
    `[stamp-dev-index] warning: fixtures/${fixture} does not exist; stamping the path anyway\n`,
  );
}

const escaped = fixtureRoot
  .replaceAll('&', '&amp;')
  .replaceAll('"', '&quot;')
  .replaceAll('<', '&lt;');

const source = readFileSync(SOURCE, 'utf8');
const stamped = source.replace(
  '<meta name="skill-map-mode" content="live" />',
  `<meta name="skill-map-mode" content="live" />\n    <meta name="skill-map-scope" content="${escaped}" />`,
);
if (stamped === source) {
  throw new Error('[stamp-dev-index] anchor meta (skill-map-mode) not found in src/index.html');
}

writeFileSync(
  TARGET,
  `<!-- GENERATED by scripts/stamp-dev-index.mjs, do not edit (gitignored). -->\n${stamped}`,
  'utf8',
);
process.stdout.write(`[stamp-dev-index] ${fixture} -> ${fixtureRoot}\n`);
