#!/usr/bin/env node
/**
 * Codegen for the view-slot / input-type catalog mirrors.
 *
 * Single source of truth: the `oneOf` const lists in
 *   spec/schemas/view-slots.schema.json#/$defs/SlotName
 *   spec/schemas/input-types.schema.json#/$defs/InputTypeName
 * Each branch carries `{ const, description }`; the `const` is the slot /
 * input-type id and the `description` is the catalog summary surfaced by
 * `sm plugins slots list`.
 *
 * Emits two TypeScript files from that spec:
 *   src/kernel/types/view-catalog.generated.ts  (TSlotName / TInputTypeName
 *       unions + ALL_SLOT_NAMES + KNOWN_SLOT_NAMES + ALL_INPUT_TYPE_NAMES)
 *   src/cli/commands/plugins/slots-catalog.ts   (VIEW_SLOTS_CATALOG /
 *       INPUT_TYPES_CATALOG with `{ id, summary }`)
 *
 * The UI keeps a hand-authored `TSlotId` union in
 * ui/src/app/slots/slot-config.ts (its `SLOT_REGISTRY` carries UI-only
 * renderer config that cannot be derived from the spec). This script does
 * NOT generate the UI file; it only verifies the UI slot name set matches
 * the spec and reports drift.
 *
 * Run:
 *   node scripts/generate-view-catalog.js          # regenerate
 *   node scripts/generate-view-catalog.js --check  # fail CI on drift
 *
 * Wired as `view-catalog:check` in `src/package.json` (validate:compile)
 * next to `built-ins:check`, and in `.githooks/pre-commit`.
 */

import { createRequire } from 'node:module';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(HERE, '..');

// `json-schema-to-typescript` is a devDep of the `@skill-map/cli` workspace
// (src/), not of the repo root where this script lives, so resolve it through
// src/package.json rather than relying on hoisting.
const require = createRequire(resolve(REPO_ROOT, 'src/package.json'));
const { compile: compileJsonSchemaToTs } = require('json-schema-to-typescript');

const VIEW_SLOTS_SCHEMA = resolve(REPO_ROOT, 'spec/schemas/view-slots.schema.json');
const INPUT_TYPES_SCHEMA = resolve(REPO_ROOT, 'spec/schemas/input-types.schema.json');
const KERNEL_OUT = resolve(REPO_ROOT, 'src/kernel/types/view-catalog.generated.ts');
const CLI_OUT = resolve(REPO_ROOT, 'src/cli/commands/plugins/slots-catalog.ts');
const UI_SLOT_CONFIG = resolve(REPO_ROOT, 'ui/src/app/slots/slot-config.ts');

const rel = (p) => relative(REPO_ROOT, p);

/**
 * Read a `$defs.<defName>.oneOf` list of `{ const, description }` branches
 * from a parsed schema object. Returns `[{ id, summary }]` in spec order.
 */
function readOneOfEntries(schema, defName) {
  const def = schema?.$defs?.[defName];
  if (!def || !Array.isArray(def.oneOf)) {
    throw new Error(`#/$defs/${defName} has no oneOf list`);
  }
  return def.oneOf.map((branch) => {
    if (typeof branch.const !== 'string') {
      throw new Error(`#/$defs/${defName} has a non-const oneOf branch`);
    }
    return { id: branch.const, summary: String(branch.description ?? '') };
  });
}

function readSchema(path) {
  return JSON.parse(readFileSync(path, 'utf8'));
}

/** Emit a single-quoted TS string literal, escaping `\` and `'`. */
function singleQuoted(str) {
  return `'${String(str).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

function tsUnion(typeName, ids) {
  const lines = [`export type ${typeName} =`];
  ids.forEach((id, i) => {
    lines.push(`  | '${id}'${i === ids.length - 1 ? ';' : ''}`);
  });
  return lines.join('\n');
}

function tsNameArray(constName, typeName, ids) {
  const lines = [`export const ${constName}: ReadonlyArray<${typeName}> = [`];
  for (const id of ids) lines.push(`  '${id}',`);
  lines.push('];');
  return lines.join('\n');
}

function tsCatalog(constName, entries) {
  const lines = [`export const ${constName} = [`];
  for (const e of entries) {
    lines.push(`  { id: '${e.id}', summary: ${singleQuoted(e.summary)} },`);
  }
  lines.push('] as const;');
  return lines.join('\n');
}

const GEN_HEADER = [
  '// AUTO-GENERATED by scripts/generate-view-catalog.js. Do not edit by hand.',
  '// Regenerate with `pnpm --filter @skill-map/cli view-catalog`.',
  '// Source of truth: the `oneOf` const lists in',
  '//   spec/schemas/view-slots.schema.json#/$defs/SlotName',
  '//   spec/schemas/input-types.schema.json#/$defs/InputTypeName',
];

/**
 * Build the synthetic root schema fed to json-schema-to-typescript: an object
 * whose properties are `<slot> -> $ref payloads/<slot>`, so the generated root
 * interface IS the slot->payload map. TS cannot express two JSON-Schema
 * keywords our payloads use, so we strip them from the object-root of each
 * payload def before generating (they stay in the on-disk schema and are
 * enforced at runtime by AJV):
 *   - `anyOf`/`oneOf`/`allOf` at the object root ("at least one of icon/label/
 *     count" on the badge) would otherwise collapse the interface to an
 *     unusable `{ [k: string]: unknown }`.
 *   - `maxItems`/`minItems` are dropped via the `ignoreMinAndMaxItems` option
 *     (otherwise arrays explode into length-N tuple unions).
 */
function buildSyntheticPayloadSchema(schema) {
  const defs = JSON.parse(JSON.stringify(schema.$defs));
  for (const def of Object.values(defs.payloads ?? {})) {
    if (def && typeof def === 'object' && def.type === 'object') {
      delete def.anyOf;
      delete def.oneOf;
      delete def.allOf;
    }
  }
  const slotIds = schema.$defs.SlotName.oneOf.map((b) => b.const);
  return {
    title: 'SlotPayloadMap',
    type: 'object',
    additionalProperties: false,
    $defs: defs,
    properties: Object.fromEntries(slotIds.map((s) => [s, { $ref: `#/$defs/payloads/${s}` }])),
    required: slotIds,
  };
}

/**
 * Generate the per-slot payload interfaces + the `SlotPayloadMap` (slot ->
 * payload) + the `SlotPayload<S>` accessor, as one TS block appended to the
 * kernel generated file. Async because json-schema-to-typescript is async.
 */
async function renderPayloadTypes(viewSlotsSchema) {
  const synthetic = buildSyntheticPayloadSchema(viewSlotsSchema);
  const body = await compileJsonSchemaToTs(synthetic, 'SlotPayloadMap', {
    additionalProperties: false,
    bannerComment: '',
    declareExternallyReferenced: true,
    ignoreMinAndMaxItems: true,
    style: { singleQuote: true },
    cwd: resolve(REPO_ROOT, 'spec/schemas') + '/',
  });
  return [
    '',
    '// ---------------------------------------------------------------------------',
    '// Per-slot payload types, generated from',
    '// `view-slots.schema.json#/$defs/payloads`. TS captures the STRUCTURAL shape',
    '// only; array length caps (maxItems) and "at least one of" (anyOf) constraints',
    '// are enforced at runtime by AJV (see kernel/adapters/schema-validators.ts).',
    '// ---------------------------------------------------------------------------',
    body.trimEnd(),
    '',
    '/**',
    ' * Payload type for a given slot. `ctx.emitContribution` infers this from the',
    " * declared contribution's `slot`, so the author gets a typed payload argument.",
    ' */',
    'export type SlotPayload<S extends TSlotName> = SlotPayloadMap[S];',
    '',
  ].join('\n');
}

export function renderKernel(slots, inputs, payloadBlock) {
  const slotIds = slots.map((s) => s.id);
  const inputIds = inputs.map((s) => s.id);
  const out = [
    '/* eslint-disable */',
    ...GEN_HEADER,
    '',
    '/**',
    ' * Closed enum of view slot names. Mirror of',
    ' * `spec/schemas/view-slots.schema.json#/$defs/SlotName`.',
    ' */',
    tsUnion('TSlotName', slotIds),
    '',
    '/**',
    ' * Runtime mirror of `TSlotName`. Single source of truth for every',
    ' * consumer that compares an untrusted string against the closed',
    ' * catalog at runtime (manifest validation, `sm plugins doctor` drift',
    ' * checks, `ctx.emitContribution` payload routing).',
    ' */',
    tsNameArray('ALL_SLOT_NAMES', 'TSlotName', slotIds),
    '',
    '/**',
    ' * Set form of `ALL_SLOT_NAMES` for O(1) membership checks. Typed as',
    ' * `ReadonlySet<string>` (not `ReadonlySet<TSlotName>`) because callers',
    ' * feed it untrusted strings pulled from plugin manifests.',
    ' */',
    'export const KNOWN_SLOT_NAMES: ReadonlySet<string> = new Set(ALL_SLOT_NAMES);',
    '',
    '/**',
    ' * Closed enum of input-type names for plugin settings. Mirror of',
    ' * `spec/schemas/input-types.schema.json#/$defs/InputTypeName`.',
    ' */',
    tsUnion('TInputTypeName', inputIds),
    '',
    '/** Runtime mirror of `TInputTypeName`. */',
    tsNameArray('ALL_INPUT_TYPE_NAMES', 'TInputTypeName', inputIds),
    payloadBlock,
  ];
  return out.join('\n');
}

export function renderCli(slots, inputs) {
  const out = [
    ...GEN_HEADER,
    '// Each summary is the spec description for that slot / input-type.',
    '// Edit the spec, then regenerate. Browse via `sm plugins slots list`.',
    '',
    tsCatalog('VIEW_SLOTS_CATALOG', slots),
    '',
    tsCatalog('INPUT_TYPES_CATALOG', inputs),
    '',
  ];
  return out.join('\n');
}

/** Parse the hand-authored `TSlotId` union from the UI slot-config file. */
export function parseUiSlotUnion(src) {
  const m = src.match(/export type TSlotId\s*=([\s\S]*?);/);
  if (!m) throw new Error('TSlotId union not found in ui slot-config.ts');
  return new Set([...m[1].matchAll(/'([^']+)'/g)].map((x) => x[1]));
}

export function diffSets(expected, actual) {
  const added = [...actual].filter((x) => !expected.has(x)).sort();
  const removed = [...expected].filter((x) => !actual.has(x)).sort();
  return { added, removed };
}

function checkFile(path, content) {
  const current = existsSync(path) ? readFileSync(path, 'utf8') : '';
  if (current === content) return false;
  process.stderr.write(
    `${rel(path)} is stale. Run \`pnpm --filter @skill-map/cli view-catalog\` and commit the result.\n`,
  );
  return true;
}

async function main() {
  const viewSlotsSchema = readSchema(VIEW_SLOTS_SCHEMA);
  const slots = readOneOfEntries(viewSlotsSchema, 'SlotName');
  const inputs = readOneOfEntries(readSchema(INPUT_TYPES_SCHEMA), 'InputTypeName');
  const payloadBlock = await renderPayloadTypes(viewSlotsSchema);
  const kernelContent = renderKernel(slots, inputs, payloadBlock);
  const cliContent = renderCli(slots, inputs);

  const slotIds = new Set(slots.map((s) => s.id));
  const uiDiff = diffSets(slotIds, parseUiSlotUnion(readFileSync(UI_SLOT_CONFIG, 'utf8')));
  const uiDrifted = uiDiff.added.length > 0 || uiDiff.removed.length > 0;
  const uiMsg =
    `UI slot union (${rel(UI_SLOT_CONFIG)}) is out of sync with the spec.\n` +
    (uiDiff.removed.length ? `  missing in UI: ${uiDiff.removed.join(', ')}\n` : '') +
    (uiDiff.added.length ? `  extra in UI:   ${uiDiff.added.join(', ')}\n` : '') +
    '  Edit TSlotId + SLOT_REGISTRY in slot-config.ts by hand (the UI renderer config is UI-only).\n';

  const mode = process.argv[2];
  if (mode === '--check') {
    let stale = false;
    if (checkFile(KERNEL_OUT, kernelContent)) stale = true;
    if (checkFile(CLI_OUT, cliContent)) stale = true;
    if (uiDrifted) {
      process.stderr.write(uiMsg);
      stale = true;
    }
    if (stale) process.exit(1);
    process.stdout.write(`view catalog mirrors in sync (${slots.length} slots, ${inputs.length} input-types).\n`);
    return;
  }

  writeFileSync(KERNEL_OUT, kernelContent);
  writeFileSync(CLI_OUT, cliContent);
  process.stdout.write(
    `wrote ${rel(KERNEL_OUT)} + ${rel(CLI_OUT)} (${slots.length} slots, ${inputs.length} input-types).\n`,
  );
  if (uiDrifted) process.stderr.write(`WARNING: ${uiMsg}`);
}

const isMain = import.meta.url === pathToFileURL(process.argv[1] ?? '').href;
if (isMain) {
  main().catch((err) => {
    process.stderr.write(`${err?.stack ?? err}\n`);
    process.exit(1);
  });
}
